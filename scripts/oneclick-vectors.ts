/**
 * Writes contracts/res/oneclick-quote-vectors.json, shared by the registry's Rust tests and the
 * TypeScript tests: 1Click's real quote-signature format (packages/core/src/oneclick-quote.ts).
 *
 *   pnpm oneclick:vectors
 *
 * - `live`: a real, non-dry 1Click quote (data/oneclick/live-quote-2026-11-11.json, nothing was
 *   deposited), its Q, signature and 1Click's published key; a tampered Q must fail.
 * - `sim`: quotes in the same format signed with a fixed test seed, for a sale the registry tests
 *   can bind: one ordinary, one whose cost is above the fee bound.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import {
  base58Decode,
  formatNearKey,
  hexToBytes,
  ONECLICK_LIVE_QUOTE_KEY,
  type OneClickQuoteLike,
  oneclickQuoteMessage,
  oneclickSignedBytes,
  parseNearKey,
  parseQuoteTerms,
  quoteCostWithinBound,
} from '@glidepath/core';
import { ed25519 } from '@noble/curves/ed25519.js';

const root = new URL('../', import.meta.url);
const live = JSON.parse(
  readFileSync(new URL('data/oneclick/live-quote-2026-11-11.json', root), 'utf8'),
) as OneClickQuoteLike & { signature: string };
const liveQ = oneclickQuoteMessage(live);
const liveKey = parseNearKey(ONECLICK_LIVE_QUOTE_KEY).bytes;
const liveSig = base58Decode(live.signature.slice('ed25519:'.length));
const tamperedQ = liveQ.replace(/example\.near/g, 'evil.near');
if (!ed25519.verify(liveSig, oneclickSignedBytes(liveQ), liveKey))
  throw new Error('The live quote no longer verifies: the Q builder is wrong');
if (ed25519.verify(liveSig, oneclickSignedBytes(tamperedQ), liveKey))
  throw new Error('A tampered live quote verified');

const seed = hexToBytes('2c'.repeat(32));
const simKey = formatNearKey('ed25519', ed25519.getPublicKey(seed));
/** A quote for the registry tests' standard sale: 10 tokens for at least 15 USDC. */
const simResponse = (amountOutUsd: string): OneClickQuoteLike => ({
  timestamp: '2026-09-21T13:46:40.000Z',
  quoteRequest: {
    dry: false,
    swapType: 'EXACT_INPUT',
    slippageTolerance: 100,
    originAsset: 'nep141:token.test.near',
    depositType: 'ORIGIN_CHAIN',
    destinationAsset: 'nep141:usdc.near',
    amount: '10000000000000000000',
    refundTo: 'p1.registry.test.near',
    refundType: 'ORIGIN_CHAIN',
    recipient: 'beneficiary.test.near',
    recipientType: 'DESTINATION_CHAIN',
    deadline: '2026-09-21T13:56:40.000Z',
    quoteWaitingTimeMs: 0,
    appFees: [{ recipient: 'sim-fees.test.near', fee: 20 }],
  },
  quote: {
    amountIn: '10000000000000000000',
    amountInFormatted: '10.0',
    amountInUsd: '15.200000000000',
    minAmountIn: '10000000000000000000',
    amountOut: '15150000',
    amountOutFormatted: '15.15',
    amountOutUsd,
    minAmountOut: '15000000',
    timeEstimate: 20,
    refundFee: '0',
    withdrawFee: '0',
    deadline: '2026-09-21T13:56:40.000Z',
    timeWhenInactive: '2026-09-21T13:56:40.000Z',
    depositAddress: 'venue.test.near',
  },
});
const simCase = (amountOutUsd: string) => {
  const q = oneclickQuoteMessage(simResponse(amountOutUsd));
  return {
    q,
    signed_message: new TextDecoder().decode(oneclickSignedBytes(q)),
    signature: formatNearKey('ed25519', ed25519.sign(oneclickSignedBytes(q), seed)),
    cost_within_bound: quoteCostWithinBound(parseQuoteTerms(q)),
  };
};

const out = {
  about:
    'Generated by scripts/oneclick-vectors.ts. 1Click quote signatures: ed25519 over the UTF-8 text of base58(sha256(Q)); see packages/core/src/oneclick-quote.ts.',
  live: {
    source:
      'data/oneclick/live-quote-2026-11-11.json (a real non-dry quote; nothing was deposited)',
    public_key: ONECLICK_LIVE_QUOTE_KEY,
    q: liveQ,
    signed_message: new TextDecoder().decode(oneclickSignedBytes(liveQ)),
    signature: live.signature,
    cost_within_bound: quoteCostWithinBound(parseQuoteTerms(liveQ)),
    tampered_q: tamperedQ,
  },
  sim: {
    seed_hex: '2c'.repeat(32),
    public_key: simKey,
    ordinary: simCase('15.150000000000'),
    // 15.20 in, 14.00 out: an 8% cost, far above 50 bps + $1.00 (the bound allows about 1.076).
    too_costly: simCase('14.000000000000'),
  },
};
writeFileSync(
  new URL('contracts/res/oneclick-quote-vectors.json', root),
  `${JSON.stringify(out, null, 2)}\n`,
);
console.log('wrote contracts/res/oneclick-quote-vectors.json');
